#!/usr/bin/env python3
"""Fytoon static site generator. Rebuilds every player-facing page from the static catalog.
Inputs: assets/js/catalog.js, assets/js/games.js (catalog), fyzen/game-details.json (copy extracted once),
fyzen/stories.json (Stories catalog).
Output: index, category-*, popular, new, favorites, recent, search, all-games, daily, profile,
privacy, terms, advertise, 404, category, game-*, stories, story-*.html. Static only, no network calls, noindex everywhere.
Run from the repo root: python3 fyzen/build_site.py"""
import json, re, html, os, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
E = lambda s: html.escape(str(s), quote=True)
def brand(s): return s.replace('Playtoom', 'Fytoon').replace('playtoom', 'fytoon').replace('Fyzen', 'Fytoon')

cat = open('assets/js/catalog.js').read(); cat = json.loads(cat[cat.index('{'):cat.rindex('}') + 1])
gm = open('assets/js/games.js').read()
old = open('fyzen/catalog-data.js').read(); old = json.loads(old[old.index('{'):old.rstrip().rstrip(';').rindex('}') + 1])
ENGINE = {g['s']: g['engine'] for g in old['games']}
DET = json.load(open('fyzen/game-details.json'))
STORIES = json.load(open('fyzen/stories.json'))

GAMES = []
for g in cat['games']:
    s = g['s']
    m = re.search(r'"%s":\{[^}]*page: "([^"]+)",\s*live: (\w+)\s*, orientation: "(\w+)"' % re.escape(s), gm)
    page, live, orient = m.group(1), m.group(2) == 'true', m.group(3)
    if not live or not os.path.exists(os.path.join(s, 'index.html')): continue
    d = DET.get(s, {})
    GAMES.append(dict(s=s, name=g['name'], kind=g['kind'], desc=brand(g['tag']), types=g['types'],
        engine=ENGINE.get(s, 'Hexan.js'), page=page, orientation=orient, isNew=g['isNew'],
        tile=g['tile'], thumb=g['thumb'], wide=g['wide'], daily=g['daily'], syn=g.get('syn', []),
        about=[brand(a) for a in d.get('about', [])], how=d.get('how', []), keys=d.get('keys', [])))
for g in GAMES:
    for k in ('tile', 'thumb', 'wide'):
        assert os.path.exists(g[k]), g[k]
BY = {g['s']: g for g in GAMES}
TYPES = [dict(id=t['id'], label=t['label'], icon=t['icon'], color=t['color'], desc=t.get('desc', ''),
              games=[s for s in t['games'] if s in BY]) for t in cat['types']]
TYPE = {t['id']: t for t in TYPES}
NEWEST = [s for s in cat['newest'] if s in BY]
ENGINES = {}
for g in GAMES: ENGINES[g['engine']] = ENGINES.get(g['engine'], 0) + 1
CAT_ICON = {'puzzle': 'puzzle', 'action': 'arcade', 'racing': 'car', 'sports': 'sports', 'strategy': 'strategy',
            'merge': 'merge', 'word': 'word', 'relax': 'leaf'}
for t in TYPES: t['icon'] = CAT_ICON.get(t['id'], 'gamepad')

# Client data file (used by components.js for local-only rows: saved, recent, search, filters)
client = dict(games=[{k: g[k] for k in ('s', 'name', 'kind', 'desc', 'types', 'engine', 'page', 'orientation', 'isNew', 'tile', 'thumb', 'daily', 'syn')} for g in GAMES],
              types=[{k: t[k] for k in ('id', 'label', 'icon', 'color')} | {'count': len(t['games'])} for t in TYPES], newest=NEWEST)
open('fyzen/catalog-data.js', 'w').write('/* Fytoon catalog, generated by fyzen/build_site.py from the static catalog. Real titles, kinds, categories, engines and art only.\n   No ratings, play counts or session numbers exist yet, so none are shown. */\nwindow.FZ_DATA=' + json.dumps(client, ensure_ascii=False, separators=(',', ':')) + ';\n')

V = '7'  # cache-buster for css/js/brand assets
def I(n, cls=''): return '<svg class="fz-i%s" aria-hidden="true" focusable="false"><use href="#fz-i-%s"/></svg>' % (' ' + cls if cls else '', n)
def gp(g): return 'game-%s.html' % g['page']
def tlabel(g): return TYPE[g['types'][0]]['label']

def img(src, alt='', eager=False):
    return '<img src="%s" alt="%s"%s decoding="async">' % (E(src), E(alt), '' if eager else ' loading="lazy"')

def card(g):
    new = '<span class="fz-badge fz-badge--new">New</span>' if g['s'] in NEWEST else ''
    return ('<article class="fz-card" data-fz-engine="%s" data-fz-types="%s"><a class="fz-card-link" href="%s" aria-label="Play %s"></a>'
            '<div class="fz-thumb">%s<div class="fz-tl"><span class="fz-badge fz-badge--engine">%s</span>%s</div>'
            '<div class="fz-tr"><button class="fz-icon-btn fz-bookmark" type="button" data-fz-bookmark="%s" aria-pressed="false" aria-label="Add to Saved">%s</button></div></div>'
            '<div class="fz-card-body"><h3 class="fz-card-title">%s</h3><div class="fz-card-meta"><span>%s</span><span class="fz-card-cat">%s</span></div></div></article>') % (
        E(g['engine']), E(' '.join(g['types'])), gp(g), E(g['name']), img(g['tile']), E(g['engine']), new, E(g['s']), I('bookmark'), E(g['name']), E(g['kind']), E(tlabel(g)))

def spot(g, label='Featured'):
    return ('<article class="fz-spot">%s<div class="fz-spot-tags"><span class="fz-badge fz-badge--featured">%s</span><span class="fz-eng">%s</span></div>'
            '<h3 class="fz-spot-title">%s</h3><p class="fz-spot-desc">%s</p><div class="fz-spot-foot"><span class="fz-spot-kind">%s · %s</span>'
            '<a class="fz-btn fz-btn--primary" href="%s">%sPlay</a></div></article>') % (
        img(g['wide'], '', True), E(label), E(g['engine']), E(g['name']), E(g['desc']), E(g['kind']), E(tlabel(g)), gp(g), I('play'))

def rec(g):
    return '<a class="fz-rec" href="%s"><div class="fz-thumb">%s</div><div><b>%s</b><small>%s · %s</small></div></a>' % (gp(g), img(g['thumb']), E(g['name']), E(g['engine']), E(tlabel(g)))

def grid(games): return '<div class="fz-grid">%s</div>' % ''.join(card(g) for g in games)

