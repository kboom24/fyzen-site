ORIENT = {'any': ('Any', 'Phone, tablet, desktop'), 'portrait': ('Portrait', 'Best held upright'), 'landscape': ('Landscape', 'Best turned sideways')}
def game_page(g):
    t = TYPE[g['types'][0]]
    recs = [BY[s] for s in t['games'] if s != g['s']]
    if len(recs) < 6: recs += [x for x in ALL if x['s'] != g['s'] and x not in recs][:6 - len(recs)]
