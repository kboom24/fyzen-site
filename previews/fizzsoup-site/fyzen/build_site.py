def sec(icon, title, meta, inner, extra=''):
    return '<section%s><div class="fz-section-head"><h2>%s%s</h2>%s</div>%s</section>' % (
        extra, I(icon), title, '<span class="fz-meta">%s</span>' % meta if meta else '', inner)

def page_head(icon, title, sub):
    return '<div class="fz-page-head"><h1>%s%s</h1>%s</div>' % (I(icon), E(title), '<p>%s</p>' % sub if sub else '')

def write(fn, s):
    assert 'laytoom' not in s, fn
    assert 'Fytoon' not in s, fn
    assert 'Fyzen' not in s, fn
    open(fn, 'w').write(s)

